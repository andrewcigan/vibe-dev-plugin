#!/bin/bash
# Определение «команда пишет в файл X» (v9 F1.3) — ОДИН словарь на весь плагин.
#
# ЗАЧЕМ ОБЩИЙ. Такой детектор уже жил внутри enforcement-config-protect. Второй экземпляр
# в другом стороже означал бы, что дыру придётся чинить дважды и однажды забудут — ровно
# класс «чинили пример, а не класс». Здесь единственное место, куда добавляется новый глагол.
#
# ЧЕСТНАЯ ГРАНИЦА. Это распознавание НАМЕРЕНИЯ по тексту команды: оно ловит перенаправление,
# копирование, переименование, правку на месте. Оно принципиально не ловит всё (python -c с
# открытием файла, здесь-документ, интерпретатор в интерпретаторе). Поэтому детектор — первый
# рубеж, а вторым идёт сверка состояния файла после выполнения (PostToolUse): она не зависит
# от того, угадали ли мы форму команды.

# cmd_writes_to <команда> <regex-пути> -> 0 если команда пишет в этот путь
cmd_writes_to() {
  local cmd="$1" f="$2"
  # Цель — ЗАПИСЬ В ЭТОТ файл, а не упоминание его имени где-то в команде. Широкий шаблон
  # («оператор ... где-то дальше имя») ловил любую команду, в тексте которой встречается имя:
  # правка исходников плагина блокировалась собственным сторожем.
  printf '%s' "$cmd" | grep -qE "(>>?|tee)[[:space:]]*[\"']?[^[:space:]|;&\"']*${f}" 2>/dev/null && return 0
  printf '%s' "$cmd" | grep -qE "(cp|mv|install|ln|dd|touch)[[:space:]][^|;&]*[[:space:]][\"']?[^[:space:]|;&\"']*${f}" 2>/dev/null && return 0
  printf '%s' "$cmd" | grep -qE "sed[^|;&]*-i[^|;&]*${f}" 2>/dev/null && return 0
  # Интерпретатор: точка с запятой и труба живут ВНУТРИ кавычек кода, поэтому ограничивать
  # сегмент нельзя. Смотрим на связку «интерпретатор + файл + признак записи».
  if printf '%s' "$cmd" | grep -qE "(python3?|node|perl|ruby)" 2>/dev/null \
     && printf '%s' "$cmd" | grep -qE "$f" 2>/dev/null \
     && printf '%s' "$cmd" | grep -qE "(open[^)]*[\"']w[\"']|dump|write|truncate|writeFile|>>?)" 2>/dev/null; then
    return 0
  fi
  printf '%s' "$cmd" | grep -qE "(jq|yq)[^|;&]*${f}" 2>/dev/null && return 0
  return 1
}
