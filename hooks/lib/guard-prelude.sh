#!/bin/bash
# Пролог сторожа (v9 F1.2) — «проверка не выполнилась» перестаёт выглядеть как «нарушений нет».
#
# ЧТО БЫЛО. Каждый сторож заканчивался безусловным `exit 0`. При сломанном окружении (jq или
# python3 недоступны/возвращают ошибку) сторож молча доходил до конца и отвечал «возражений
# нет». Замерено на движке 2.1.220 и 2.1.259: 26 из 26 сторожей ведут себя так. Прицельно:
# защита от боевого ключа в исходниках при сломанном jq не выдаёт ничего, и ключ проходит.
# Обвязка fail-loud этого не видела, потому что ловила только ненулевой код возврата.
#
# ЧТО СТАЛО. Две вещи:
#   guard_require_tools — на входе проверяет, что нужные утилиты РАБОТАЮТ (не просто есть в
#     PATH: заглушка тоже «есть»). Не работают → выход с кодом 90, который обвязка трактует
#     как «сторож не выполнил проверку», поднимает тревогу и пишет crash-артефакт.
#   guard_done — единственный штатный выход. Печатает маркер завершения в stderr; отсутствие
#     маркера при нулевом коде означает, что сторож умер на полпути.
#
# ЧЕСТНАЯ ГРАНИЦА. Это закрывает класс «сломанное окружение» — тот, что измерен. Случай
# «утилита работает, но упала на конкретном входе, а скрипт продолжил» маркером не ловится:
# для него нужна проверка кода возврата в каждой точке вызова. Не заявляем закрытым.

GUARD_DONE_MARKER="__VIBE_GUARD_DONE__"
GUARD_RC_TOOL_BROKEN=90

# guard_require_tools jq python3 ...
guard_require_tools() {
  local t
  for t in "$@"; do
    case "$t" in
      jq)      jq --version      >/dev/null 2>&1 || guard_tool_broken "jq" ;;
      python3) python3 -c 'pass'  >/dev/null 2>&1 || guard_tool_broken "python3" ;;
      *)       command -v "$t"   >/dev/null 2>&1 || guard_tool_broken "$t" ;;
    esac
  done
}

guard_tool_broken() {
  printf 'утилита «%s» недоступна или не работает — проверка НЕ выполнена\n' "$1" >&2
  exit "$GUARD_RC_TOOL_BROKEN"
}

# Штатное завершение: подтверждает, что сторож дошёл до конца своей логики.
guard_done() {
  printf '%s\n' "$GUARD_DONE_MARKER" >&2
  exit 0
}
