#!/bin/bash
# Разросшийся журнал виден при старте сессии (v9 F5.3).
#
# ЗАЧЕМ. Журналы читаются целиком при работе, и их размер прямо переводится в расход контекста.
# Замер по живым проектам: журнал фич дорос до 1,16 МБ — примерно 290 тысяч токенов на каждое
# чтение; рядом журнал сессии 648 КБ и журнал ошибок 387 КБ. Механизм ротации существовал, но
# искал состояние, которого нет в графе переходов, и не срабатывал ни разу — а молча растущий
# файл никто не замечает, потому что он не ломается, а просто дорожает.
#
# ЧТО ДЕЛАЕТ. При старте сессии сравнивает размеры журналов с порогом и говорит, сколько это
# стоит и какой командой чинится. Не блокирует: разросшийся журнал — не нарушение, а счёт.
#
# Аргументы: $1=cwd. Печатает текст-inject или пусто.
set -u
. "$(dirname "${BASH_SOURCE[0]}")/../lib/guard-prelude.sh"
CWD="${1:-$PWD}"
THRESHOLD=204800   # 200 КБ ≈ 50 тысяч токенов на одно чтение

size_of() { [ -f "$1" ] && wc -c < "$1" 2>/dev/null | tr -d ' ' || echo 0; }
human() { python3 -c "
import sys
n=int(sys.argv[1])
print(f'{n/1048576:.2f} МБ' if n>=1048576 else f'{n//1024} КБ')" "$1" 2>/dev/null || echo "$1 б"; }

REPORT=""
for pair in "feature_list.json|журнал фич|bash scripts/archive-features.sh" \
            "SESSION.md|журнал сессии|/checkpoint (ротация завершённого в архив)" \
            "error-journal.md|журнал ошибок|/lessons (свод повторов, остальное в архив)"; do
  f="${pair%%|*}"; rest="${pair#*|}"; label="${rest%%|*}"; fix="${rest##*|}"
  sz="$(size_of "$CWD/$f")"
  if [ "$sz" -gt "$THRESHOLD" ]; then
    REPORT="${REPORT}
• ${label}: $(human "$sz") — примерно $((sz/4000)) тысяч токенов при каждом чтении. Чинится: ${fix}"
  fi
done

if [ -n "$REPORT" ]; then
  printf 'Журналы проекта разрослись и дорого обходятся в каждой сессии:%s\n\nЭто не поломка, а счёт: файлы читаются целиком. Разбор стоит сделать до крупной работы, а не после.\n' "$REPORT"
fi
guard_done
